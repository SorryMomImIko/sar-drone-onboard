#pragma once
// TelemetrySource.hpp - граница между "откуда берём телеметрию" и
// "что с ней делаем дальше".
//
// Всё, что ниже этой границы (геопривязка, сращивание с кадром, отправка на
// землю), работает с двумя кольцевыми буферами и о протоколе ничего не знает.
// Поэтому смена протокола - это ОДИН новый файл с реализацией этого
// интерфейса плюс одна строка в make_telemetry_source(). Ни main.cpp, ни
// геометрию, ни буферы трогать не придётся.
//
// ЧТО ОБЯЗАНА ДЕЛАТЬ ЛЮБАЯ РЕАЛИЗАЦИЯ:
//   1. Класть углы в AttitudeBuffer, координаты - в PositionBuffer,
//      ОТДЕЛЬНО (почему два буфера, а не один - см. TelemetryBuffers.hpp).
//   2. Ставить в t_us время ПО ЧАСАМ ПЛАТЫ (now_us()), а не по часам
//      автопилота. Если автопилот даёт своё время - свести его с платой,
//      как это делает MavlinkThread.
//   3. Не блокировать ничей чужой поток: своя нить, короткий мьютекс на push.
//   4. Переживать пропажу устройства. По USB это не редкость, а норма:
//      разъём дёрнули, автопилот перезагрузился - /dev/ttyACM0 исчез и
//      появился снова. Реализация обязана переоткрывать порт сама.

#include "TelemetryBuffers.hpp"

#include <memory>
#include <string>

namespace sar {

class ITelemetrySource {
public:
    virtual ~ITelemetrySource() = default;

    // uri - что открывать. Примеры:
    //   "/dev/ttyS3"                      UART на плате
    //   "/dev/serial/by-id/usb-..."       автопилот по USB (см. ниже)
    //   "udp:0.0.0.0:14550"               симулятор при отладке
    virtual bool open(const std::string& uri) = 0;

    virtual void start() = 0;
    virtual void stop()  = 0;

    // Автопилот отвечает (видели пакет недавно)
    virtual bool link_ok() const = 0;
    // Часы автопилота сведены с часами платы. Если протокол не передаёт
    // своего времени и метка ставится по приёму - возвращать true.
    virtual bool clock_locked() const = 0;
    // Сколько разобранных пакетов всего - первое, на что смотреть,
    // когда "не работает": ноль означает, что не тот порт или не тот протокол.
    virtual uint64_t messages() const = 0;

    // Имя протокола для консоли
    virtual const char* name() const = 0;
};

// ЗАЧЕМ ИСКАТЬ ПОРТ ЧЕРЕЗ /dev/serial/by-id/
//
// Номер в /dev/ttyACM0 зависит от порядка подключения устройств. Воткнули
// второй USB-прибор, перезагрузились - автопилот стал ttyACM1, и программа
// молча читает не оттуда. Путь в /dev/serial/by-id/ привязан к модели и
// серийному номеру устройства и не меняется:
//
//   ls -l /dev/serial/by-id/
//   lrwxrwxrwx ... usb-Hex_ProfiCNC_CubeOrange_1A002B-if00 -> ../../ttyACM0
//
// В боевой конфигурации указывать имя оттуда целиком.

// Выбор реализации по названию протокола - в TelemetrySourceFactory.hpp.
// Он вынесен отдельно, чтобы этот заголовок не тянул за собой заголовки
// MAVLink: геометрии и буферам они не нужны.

} // namespace sar
